def email_text(lang: str | None, section: str, key: str, *, count: int | None = None, variant: str | None = None) -> str:
    """One string, falling back from the learner's language to English and
    from the section to `common`."""
    candidates = []
    if variant:
        candidates.append(f"{key}_{variant}")
    if count == 1:
        candidates.append(f"{key}_one")
    candidates.append(key)
    for language in (push_language(lang), "en"):
        table = COPY[language]
        for name in candidates:
            for part in (section, "common"):
                value = table.get(part, {}).get(name)
                if value is not None:
                    return value
    if key == "title":
        # A page title that would only repeat the subject is not written twice.
        return email_text(lang, section, "subject", count=count, variant=variant)
    raise KeyError(f"email copy {section}.{key} is missing in English")


def section_keys(section: str) -> set[str]:
    """Every base key a section can render, so templates may use any of them."""
    names = set(COPY["en"].get(section, {})) | set(COPY["en"]["common"])
    return {re.sub(r"_(?:one|d\d)$", "", n) for n in names}
